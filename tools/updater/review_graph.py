"""A map of how the projects on this computer connect, generated from their manifests and review folders (never drawn by hand).

`mermaid(projects)` returns a Markdown file with one Mermaid diagram (GitHub draws it, in private repositories too). Nodes are projects,
labelled with their type and how many review items are open; the Updater is a node that keeps every project current; an arrow
"reviews in" goes from a project to the repository that holds its reviews. Because it is generated, it cannot go stale: run it again.
"""
import re

import review_projects as rp
import review_status as rs


def node_id(text):
    return 'p_' + re.sub(r'[^A-Za-z0-9]', '_', text)


def label(text):
    return re.sub(r'[<>"`|\[\]{}()]', '', str(text))[:60]


def open_count(project, projects):
    loc = rp.review_location(project, projects)
    return sum(len(r['open']) for r in rs.scan(loc['path'])) if loc['path'] else 0


def mermaid(projects, generated=''):
    lines = ['# Project map', '', 'Generated by `review.py graph`%s. Do not edit: run it again.' % (' on ' + generated if generated else ''), '',
             '```mermaid', 'flowchart LR', '  upd([Updater: rules, tools, review steps])']
    by_id = {p['id']: node_id(p['id']) for p in projects}
    for p in projects:
        kind = label(p['meta'].get('type') or 'project')
        n = open_count(p, projects)
        lines.append('  %s["%s<br/>%s%s"]:::%s' % (by_id[p['id']], label(p['name']), kind, (' - %d open' % n) if n else '', re.sub(r'\W', '', kind) or 'project'))
    for p in projects:
        pid = by_id[p['id']]
        lines.append('  upd -.-> %s' % pid)
        loc = rp.review_location(p, projects)
        if loc['repo_path'] and loc['repo_path'] != p['folder']:
            target = next((q for q in projects if q['folder'] == loc['repo_path']), None)
            if target:
                lines.append('  %s -->|reviews in| %s' % (pid, by_id[target['id']]))
    lines += ['  classDef product fill:#dbe7ff,stroke:#1d4ed8', '  classDef tool fill:#dff5e6,stroke:#176b3a', '  classDef data fill:#fff1d6,stroke:#8a5a00',
              '  classDef project fill:#eee,stroke:#555', '```', '', 'Dotted arrows: the Updater keeps the project current. Solid arrows: where its reviews are kept.', '']
    return '\n'.join(lines)
